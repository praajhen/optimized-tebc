

load ('C:\TEBC_project\intermediate_files\age,group,n1p2.mat')
fontName = 'Arial';
fontSize = 14;
lineW    = 1.8;

% ----------------------------------------------------------
% Colours
% ----------------------------------------------------------
youngCol     = [0 0 0];      % Young points (black)
olderCol     = [0.85 0 0];   % Older points (red)

youngMeanCol = youngCol;
olderMeanCol = olderCol;

offset = 0.18;

figure('Color','w','Position',[100 100 1200 520]);
tiledlayout(1,2,'TileSpacing','compact','Padding','compact');

%% ==========================================================
%% PANEL A : Physiological states
%% ==========================================================

nexttile
hold on

states = {'EXP-DIA','EXP-SYS','INS-DIA','INS-SYS'};

for s = 1:4

    % ---------------- Young ----------------
    idx = age==1 & group==2 & strcmp(optimal_state,states{s});
    y = n1p2(idx);
    x = s-offset + (rand(size(y))-0.5)*0.06;

   hYoung = scatter(x,y,65,'o',...
        'MarkerEdgeColor',youngCol,...
        'MarkerFaceColor','none',...
        'LineWidth',1.4);

    m = mean(y);
    sem = std(y)/sqrt(numel(y));

    errorbar(s-offset,m,sem,...
        'Color',youngMeanCol,...
        'LineWidth',lineW,...
        'CapSize',8,...
        'LineStyle','none');

    line([s-offset-0.08 s-offset+0.08],[m m],...
    'Color',youngMeanCol,...
    'LineWidth',3);

    % ---------------- Older ----------------
    idx = age==2 & group==2 & strcmp(optimal_state,states{s});
    y = n1p2(idx);
    x = s+offset + (rand(size(y))-0.5)*0.06;

   hOlder = scatter(x,y,65,'o',...
        'MarkerEdgeColor',olderCol,...
        'MarkerFaceColor','none',...
        'LineWidth',1.4);

    m = mean(y);
    sem = std(y)/sqrt(numel(y));

    errorbar(s+offset,m,sem,...
        'Color',olderMeanCol,...
        'LineWidth',lineW,...
        'CapSize',8,...
        'LineStyle','none');

    line([s+offset-0.08 s+offset+0.08],[m m],...
    'Color',olderMeanCol,...
    'LineWidth',3);

end

xlim([0.5 4.5])
ylim([0 10])
xticks(1:4)
xticklabels(states)

ylabel('Composite N1-P2 amplitude (\muV)',...
    'FontName',fontName,'FontSize',fontSize)

% title('A. Physiological state',...
%     'FontName',fontName,...
%     'FontSize',fontSize,...
%     'FontWeight','bold')

text(0.03,1,'○ Young',...
    'Units','normalized',...
    'Color',[0 0 0],...
    'FontWeight','bold',...
    'FontSize',16,...
    'VerticalAlignment','top');

text(0.03,0.94,'○ Older',...
    'Units','normalized',...
    'Color',[0.85 0 0],...
    'FontWeight','bold',...
    'FontSize',16,...
    'VerticalAlignment','top');

set(gca,...
    'FontName',fontName,...
    'FontSize',16,...
    'LineWidth',1.2,...
    'TickDir','out',...
    'Box','off')

ax = gca;
ax.YAxis.FontSize = 18;    % Change to 16, 18, or 20 as desired

%% ==========================================================
%% PANEL B : Experimental groups
%% ==========================================================

nexttile
hold on

groups = {'Control','Personalised'};

for g = 1:2

    % ---------------- Young ----------------
    idx = age==1 & group==g;
    y = n1p2(idx);
    x = g-offset + (rand(size(y))-0.5)*0.06;

  scatter(x,y,65,'o',...
        'MarkerEdgeColor',youngCol,...
        'MarkerFaceColor','none',...
        'LineWidth',1.4);

    m = mean(y);
    sem = std(y)/sqrt(numel(y));

    errorbar(g-offset,m,sem,...
        'Color',youngMeanCol,...
        'LineWidth',lineW,...
        'CapSize',8,...
        'LineStyle','none');

    line([g-offset-0.08 g-offset+0.08],[m m],...
    'Color',youngMeanCol,...
    'LineWidth',3);

    % ---------------- Older ----------------
    idx = age==2 & group==g;
    y = n1p2(idx);
    x = g+offset + (rand(size(y))-0.5)*0.06;

    scatter(x,y,65,'o',...
        'MarkerEdgeColor',olderCol,...
        'MarkerFaceColor','none',...
        'LineWidth',1.4);

    m = mean(y);
    sem = std(y)/sqrt(numel(y));

    errorbar(g+offset,m,sem,...
        'Color',olderMeanCol,...
        'LineWidth',lineW,...
        'CapSize',8,...
        'LineStyle','none');

    line([g+offset-0.08 g+offset+0.08],[m m],...
    'Color',olderMeanCol,...
    'LineWidth',3);

end

xlim([0.5 2.5])
ylim([0 10])

xticks(1:2)
xticklabels(groups)


set(gca,...
    'FontName',fontName,...
    'FontSize',18,...
    'LineWidth',1.2,...
    'TickDir','out',...
    'Box','off')

ax = gca;
ax.YAxis.FontSize = 18;    % Change to 16, 18, or 20 as desired

